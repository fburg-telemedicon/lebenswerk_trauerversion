// i18n.js lesbar bleibt: dort stehen weiterhin de/pl/en (die Ursprungssprachen)
// sowie die Logik; hier die neuen Wörterbücher.
//
// Besonderheiten:
// • de-CH (Schweiz): KEIN eigenes Wörterbuch — die Oberfläche ist Schweizer
//   Hochdeutsch, also identisch zum Deutschen bis auf das ß (das es in der
//   Schweiz nicht gibt). Deshalb wird das deutsche Wörterbuch abgeleitet
//   (`swissify`). Der Unterschied liegt woanders: STT hört Mundart (de-CH),
//   die Stimme klingt schweizerisch, und die KI antwortet in Schweizer
//   Hochdeutsch (siehe langDirective in i18n.js).
// • he/ar: Schreibrichtung rechts nach links (`rtl: true` in LANGUAGES).

// Deutsch → Schweizer Hochdeutsch: ß gibt es dort nicht.
export function swissify(obj) {
  const fix = s => s.replace(/ß/g, 'ss')
  const walk = v => {
    if (typeof v === 'string') return fix(v)
    if (typeof v === 'function') return (...a) => { const r = v(...a); return typeof r === 'string' ? fix(r) : r }
    if (Array.isArray(v)) return v.map(walk)
    if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x)]))
    return v
  }
  return { ...walk(obj), locale: 'de-CH' }
}

